import json
import os
import re
import sys
import time
from pathlib import Path

INDEX_REL = Path(".claude") / "swiftui-components.md"
CONVENTIONS_REL = Path(".claude") / "conventions.md"
SKIP_DIRS = {
    ".build", "DerivedData", "Pods", "Carthage", ".git", "node_modules",
    ".swiftpm", "build", "fastlane", "vendor", ".claude",
}
MAX_FILES = 4000

UI_PROTOCOLS = (
    "View", "ViewModifier", "ButtonStyle", "PrimitiveButtonStyle", "LabelStyle",
    "ToggleStyle", "TextFieldStyle", "ProgressViewStyle", "GroupBoxStyle",
    "MenuStyle", "PickerStyle", "ListStyle", "Shape", "InsettableShape",
    "ShapeStyle", "Layout", "Widget", "App", "Scene", "PreviewProvider",
    "DynamicProperty", "EnvironmentKey", "PreferenceKey", "Transition",
    "ViewStyle",
)
DECL_RE = re.compile(
    r"^\s*(?:public\s+|internal\s+|fileprivate\s+|private\s+|final\s+|open\s+)*"
    r"(struct|class|enum|actor)\s+([A-Z][A-Za-z0-9_]*)\s*(?:<[^>]*>)?\s*:\s*([^{]+)\{",
    re.M,
)
MODIFIER_RE = re.compile(
    r"^\s*extension\s+View\s*(?:where[^{]*)?\{(.*?)^\}", re.M | re.S
)
FUNC_RE = re.compile(r"^\s*(?:public\s+)?func\s+([a-z][A-Za-z0-9_]*)\s*[(<]", re.M)
OBSERVABLE_RE = re.compile(
    r"^\s*@Observable\s*(?:@MainActor\s*)?(?:public\s+|final\s+)*class\s+([A-Z][A-Za-z0-9_]*)", re.M
)


def read_stdin_json():
    try:
        raw = sys.stdin.read()
        return json.loads(raw) if raw.strip() else {}
    except Exception:
        return {}


def project_root(payload):
    cwd = payload.get("cwd") or os.environ.get("CLAUDE_PROJECT_DIR") or os.getcwd()
    return Path(cwd)


def is_swift_project(root: Path) -> bool:
    try:
        for entry in root.iterdir():
            n = entry.name
            if n.endswith((".xcodeproj", ".xcworkspace")) or n == "Package.swift":
                return True
        for _ in iter_swift_files(root, limit=1, max_depth=3):
            return True
    except Exception:
        pass
    return False


def iter_swift_files(root: Path, limit=MAX_FILES, max_depth=None):
    count = 0
    base_depth = len(root.resolve().parts)
    for dirpath, dirnames, filenames in os.walk(root):
        depth = len(Path(dirpath).resolve().parts) - base_depth
        if max_depth is not None and depth >= max_depth:
            dirnames[:] = []
        else:
            dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS and not d.startswith(".")]
        for f in filenames:
            if f.endswith(".swift"):
                yield Path(dirpath) / f
                count += 1
                if count >= limit:
                    return


def split_camel(name: str):
    return [t.lower() for t in re.findall(r"[A-Z][a-z0-9]*|[a-z0-9]+", name) if len(t) > 2]


def scan_file(path: Path, root: Path):
    try:
        text = path.read_text(encoding="utf-8", errors="ignore")
    except Exception:
        return []
    rel = str(path.relative_to(root))
    found = []
    for m in DECL_RE.finditer(text):
        kind_kw, name, inherits = m.group(1), m.group(2), m.group(3)
        protos = [p.strip().split("<")[0] for p in inherits.split(",")]
        ui = [p for p in protos if p in UI_PROTOCOLS]
        if ui:
            found.append((name, ui[0], rel))
    for m in OBSERVABLE_RE.finditer(text):
        found.append((m.group(1), "Observable", rel))
    for m in MODIFIER_RE.finditer(text):
        for f in FUNC_RE.finditer(m.group(1)):
            found.append((f.group(1) + "()", "View extension", rel))
    return found


def build_index(root: Path):
    entries = []
    for p in iter_swift_files(root):
        entries.extend(scan_file(p, root))
    entries.sort(key=lambda e: (e[1], e[0]))
    return entries


def write_index(root: Path, entries):
    path = root / INDEX_REL
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# SwiftUI component index",
        "Generated by swiftui-context-optimiser. Do not edit; rebuilt on each Swift file write.",
        f"Updated: {time.strftime('%Y-%m-%d %H:%M')}  Entries: {len(entries)}",
        "",
        "Name | Kind | File",
    ]
    for name, kind, rel in entries:
        lines.append(f"{name} | {kind} | {rel}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def load_index(root: Path):
    path = root / INDEX_REL
    if not path.exists():
        return None
    entries = []
    for line in path.read_text(encoding="utf-8", errors="ignore").splitlines():
        parts = [p.strip() for p in line.split(" | ")]
        if len(parts) == 3 and parts[0] not in ("Name",):
            entries.append(tuple(parts))
    return entries


def emit(obj):
    sys.stdout.write(json.dumps(obj))
    sys.stdout.flush()
